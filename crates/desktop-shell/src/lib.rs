//! 简译（translate-tool）与实时字幕（live-caption）共用的桌面基建。
//!
//! 收进来的只有**机制**，不含任何一边的业务语义。判据很简单：
//! 换个应用还能原样用的，才放这里；换个应用就得改文案或改行为的，留在应用自己那边。
//!
//! 已经踩过的反例，别再合回来：
//! - 托盘的**菜单项列表**不能共用（字幕有暂停/穿透/迷你条，简译有划词/悬停开关），
//!   共用的只是「怎么把菜单弹出来并同步拿到结果」。
//! - 字幕的 `needs_restart`（改识别/切句参数要重启进程）与简译的「保存即生效」语义相反，
//!   合成一个「保存并重启」按钮会误导用户。
//! - 字幕的透明窗每帧重算高度，跟简译固定尺寸的浮窗宿主不是一回事。

